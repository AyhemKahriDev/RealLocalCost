#!/usr/bin/env node
/* ============================================================
   pull-fx.mjs — the exchange rates, from the same free source
   ------------------------------------------------------------
   World Bank indicator PA.NUS.FCRF: "Official exchange rate (LCU
   per US$, period average)". No key, no quota.

   This is what lets the site say what a dollar-priced subscription
   really costs a Tunisian — which is the whole argument of the
   project for the services that do not price per market.

     node tools/pull-fx.mjs
   ============================================================ */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { fetchJson } from "./lib/http.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INDICATOR = "PA.NUS.FCRF";
const OUT = join(ROOT, "data", "fx.json");

async function pull(wbCode) {
  const url =
    `https://api.worldbank.org/v2/country/${wbCode}/indicator/${INDICATOR}` +
    `?format=json&per_page=200`;
  const r = await fetchJson(url, { timeout: 60000 });
  if (!r.json || !Array.isArray(r.json) || r.json.length < 2) {
    throw new Error(`no data for ${wbCode}: ${r.error || r.status}`);
  }
  const series = (r.json[1] || [])
    .filter((x) => x.value != null)
    .map((x) => [String(x.date), Number(x.value)])
    .sort((a, b) => (a[0] < b[0] ? -1 : 1));
  return series;
}

async function main() {
  const marketsRaw = JSON.parse(await readFile(join(ROOT, "data", "markets.json"), "utf8"));
  const markets = marketsRaw.markets;

  const out = {
    _comment:
      "Generated by tools/pull-fx.mjs. Local currency units per one US dollar. Do not hand-edit.",
    indicator: {
      id: INDICATOR,
      name: "Official exchange rate (LCU per US$, period average)",
      source: "World Bank, World Development Indicators",
      url: "https://data.worldbank.org/indicator/PA.NUS.FCRF",
    },
    pulledAt: new Date().toISOString().slice(0, 10),
    markets: {},
    byCurrency: {},
  };

  await Promise.all(
    Object.entries(markets).map(async ([code, m]) => {
      try {
        const series = await pull(m.wb);
        if (!series.length) throw new Error("empty");
        const [year, rate] = series[series.length - 1];
        out.markets[code] = { currency: m.currency, series, latest: { year, rate } };
        /* One rate per currency, so a price in any currency can be
           converted into any market. */
        if (!out.byCurrency[m.currency]) out.byCurrency[m.currency] = { rate, year, from: code };
      } catch (err) {
        console.log(`· ${code} FAILED — ${err.message}`);
      }
    })
  );

  await writeFile(OUT, JSON.stringify(out, null, 2) + "\n");
  console.log(
    `\nfx: ${Object.keys(out.markets).length} markets, ${Object.keys(out.byCurrency).length} currencies → ${OUT}`
  );
  for (const [cur, v] of Object.entries(out.byCurrency)) {
    console.log(`  ${cur}: ${v.rate} per USD (${v.year}, from ${v.from})`);
  }
}

main();

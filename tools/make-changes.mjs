#!/usr/bin/env node
/* ============================================================
   make-changes.mjs — derive the wire from the price history
   ------------------------------------------------------------
   The wire is never written by hand. It is computed from
   data/prices.json so the feed and the tables can never disagree.

     node tools/make-changes.mjs
   ============================================================ */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

async function main() {
  const prices = JSON.parse(await readFile(join(ROOT, "data", "prices.json"), "utf8"));
  const changes = [];

  for (const row of prices.rows || []) {
    const hist = (row.history || []).slice().sort((a, b) => (a.date < b.date ? -1 : 1));
    for (let i = 1; i < hist.length; i++) {
      const from = hist[i - 1];
      const to = hist[i];
      if (from.price === to.price) continue;
      changes.push({
        date: to.date,
        service: row.service,
        market: row.market,
        plan: row.plan,
        from: from.price,
        to: to.price,
        currency: row.currency,
        receipt: row.receipt && row.receipt.archived ? row.receipt.archived : row.receipt && row.receipt.url,
      });
    }
  }

  changes.sort((a, b) => (a.date < b.date ? 1 : -1));

  await writeFile(
    join(ROOT, "data", "changes.json"),
    JSON.stringify(
      {
        _comment: "Generated by tools/make-changes.mjs from data/prices.json. Do not hand-edit.",
        generatedAt: new Date().toISOString(),
        changes,
      },
      null,
      2
    ) + "\n"
  );
  console.log(`${changes.length} change(s) → data/changes.json`);
}

main();

#!/usr/bin/env node
/* ============================================================
   pull-income.mjs — the denominator, from a free public API
   ------------------------------------------------------------
   World Bank indicator NY.GNP.PCAP.CN = "GNI per capita (current LCU)".
   No API key, no quota, no account. It is already in local currency,
   so no FX conversion is needed and the numbers stay honest.

   We use it because it is the same measure international media use
   for "what a person earns per month" — per-capita gross national
   income, annual, divided by twelve. It is an AVERAGE, not a median.
   We label it that way everywhere it appears.
   ============================================================ */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { fetchJson } from "./lib/http.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INDICATOR = "NY.GNP.PCAP.CN";
const OUT = join(ROOT, "data", "income.json");

async function pull(wbCode) {
  const url =
    `https://api.worldbank.org/v2/country/${wbCode}/indicator/${INDICATOR}` +
    `?format=json&per_page=200`;

  let lastErr = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const r = await fetchJson(url, { timeout: 60000 });
      if (!r.json || !Array.isArray(r.json) || r.json.length < 2) {
        throw new Error(`World Bank returned no data for ${wbCode}: ${r.error || r.status}`);
      }
      const rows = r.json[1];
      const series = rows
        .filter((x) => x.value != null)
        .map((x) => [String(x.date), Math.round(Number(x.value) * 100) / 100])
        .sort((a, b) => (a[0] < b[0] ? -1 : 1));
      const meta = r.json[0] || {};
      return { series, lastUpdated: meta.lastupdated || null };
    } catch (err) {
      lastErr = err;
      if (attempt < 3) await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
  throw lastErr;
}

async function main() {
  const marketsRaw = JSON.parse(await readFile(join(ROOT, "data", "markets.json"), "utf8"));
  const markets = marketsRaw.markets;

  const out = {
    _comment:
      "Generated by tools/pull-income.mjs. Do not hand-edit: run `npm run income`.",
    indicator: {
      id: INDICATOR,
      name: "GNI per capita (current LCU)",
      source: "World Bank, World Development Indicators",
      url: "https://data.worldbank.org/indicator/NY.GNP.PCAP.CN",
      api: `https://api.worldbank.org/v2/country/{iso3}/indicator/${INDICATOR}?format=json`,
      note:
        "Per-capita gross national income in current local currency. An average per person, not a median wage. Monthly = annual / 12.",
    },
    pulledAt: new Date().toISOString().slice(0, 10),
    markets: {},
  };

  const codes = Object.entries(markets);

  await Promise.all(
    codes.map(async ([code, m]) => {
      process.stdout.write(`· ${code} `);
      try {
        const { series, lastUpdated } = await pull(m.wb);
        if (!series.length) throw new Error("empty series");
        const [year, value] = series[series.length - 1];
        out.markets[code] = {
          currency: m.currency,
          series,
          latest: { year, annual: value, monthly: Math.round((value / 12) * 100) / 100 },
          lastUpdated,
        };
        console.log(`${year}: ${value} ${m.currency}/yr → ${out.markets[code].latest.monthly}/mo`);
      } catch (err) {
        console.log(`FAILED — ${err.message}`);
      }
    })
  );

  await writeFile(OUT, JSON.stringify(out, null, 2) + "\n");
  console.log(`\nwrote ${OUT}`);
}

main();
